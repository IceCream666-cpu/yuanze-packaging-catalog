export function translateMessage(value) {
  const raw = String(value ?? '');
  if (language !== 'en') return raw;
  const trimmed = raw.trim();
  if (!trimmed || !/[\u3400-\u9fff]/u.test(trimmed)) return raw;
  const direct = dictionary.get(trimmed);
  let result = direct?.en;
  if (result == null) {
    for (const [expression, format] of patterns) {
      const match = trimmed.match(expression);
      if (match) { result = format(...match); break; }
    }
  }
  // Only split lists of recognized interface/taxonomy labels. Unknown content
  // stays untouched, including Chinese source quotes, company data and names.
  if (result == null && /[、／]| \/ | · /.test(trimmed)) {
    const pieces = trimmed.split(/(、|／| \/ | · )/);
    if (pieces.filter((_,i)=>i%2===0).every(part => dictionary.has(part)))
      result = pieces.map((part,i)=>i%2?part==='、'?', ':part==='／'?' / ':part:t(part)).join('');
  }
  if (result == null && trimmed.endsWith(' *') && dictionary.has(trimmed.slice(0,-2))) result = t(trimmed.slice(0,-2))+' *';
  if (result == null) return raw;
  return raw.slice(0,raw.indexOf(trimmed)) + result + raw.slice(raw.indexOf(trimmed)+trimmed.length);
}

const textSources = new WeakMap(), attributeSources = new WeakMap();
const skipSelector = 'script,style,textarea,pre,code,[data-i18n-skip],[translate="no"],.raw,.source-box,.source-line,.image-file-path,.price-entry>span:not(.price-source),.pricing-original .price-value';
const translatedAttributes = ['aria-label','title','placeholder','alt'];
function sourceValue(store, key, current) {
  const saved = store.get(key);
  return saved && current === saved.rendered ? saved.original : current;
}
function localizeText(node) {
  const parent = node.parentElement;
  if (!parent || parent.closest(skipSelector) && !parent.closest('[data-i18n-ui]')) return;
  const original = sourceValue(textSources,node,node.nodeValue);
  const rendered = translateMessage(original);
  // An option with no explicit value inherits textContent. Freeze the original
  // value before localizing its label so form posts and filters remain canonical.
  if (parent.tagName === 'OPTION' && !parent.hasAttribute('value')) parent.setAttribute('value',parent.textContent);
  textSources.set(node,{original,rendered});
  if (node.nodeValue !== rendered) node.nodeValue = rendered;
}
function localizeAttributes(element) {
  if (element.closest('[data-i18n-skip],[translate="no"]')) return;
  let saved = attributeSources.get(element);
  if (!saved) { saved = new Map(); attributeSources.set(element,saved); }
  for (const key of translatedAttributes) {
    if (!element.hasAttribute(key) || key==='alt' && element.hasAttribute('data-source-alt')) continue;
    const original = sourceValue(saved,key,element.getAttribute(key));
    const rendered = translateMessage(original);
    saved.set(key,{original,rendered});
    if (element.getAttribute(key)!==rendered) element.setAttribute(key,rendered);
  }
}
export function localize(root = globalThis.document) {
  if (!root) return;
  if (root.nodeType === 3) { localizeText(root); return; }
  if (root.nodeType === 1) localizeAttributes(root);
  for (const element of root.querySelectorAll?.('*') || []) localizeAttributes(element);
  const doc = root.ownerDocument || root;
  if (!doc.createTreeWalker) return;
  const walker = doc.createTreeWalker(root,4);
  let node; while ((node = walker.nextNode())) localizeText(node);
}
function syncDocumentLanguage() {
  if (!globalThis.document) return;
  document.documentElement.lang = language === 'en' ? 'en' : 'zh-CN';
  document.querySelectorAll('[data-language-switch]').forEach(button => {
    button.textContent = language === 'en' ? '中文' : 'English';
    button.lang = language === 'en' ? 'zh-CN' : 'en';
    button.setAttribute('aria-label', language === 'en' ? 'Switch to Chinese' : '切换到英文');
    button.title = language === 'en' ? 'Switch to Chinese' : '切换到英文';
  });
}
export function setLanguage(next) {
  if (!['zh','en'].includes(next)) return;
  language = next;
  try { globalThis.localStorage?.setItem(LANGUAGE_STORAGE_KEY,language); } catch {}
  syncDocumentLanguage();
  for (const listener of listeners) listener(language);
  localize();
}
export function installLanguageSwitch(container) {
  if (!globalThis.document || !container) return null;
  const existing = container.querySelector('[data-language-switch]');
  if (existing) return existing;
  const button = document.createElement('button');
  button.type = 'button'; button.className = 'language-switch';
  button.dataset.languageSwitch = ''; button.dataset.i18nSkip = '';
  button.addEventListener('click', () => setLanguage(language === 'en' ? 'zh' : 'en'));
  container.append(button); syncDocumentLanguage();
  return button;
}
export function startLocalization({container} = {}) {
  if (!globalThis.document) return;
  if (container) installLanguageSwitch(container);
  const footer=document.querySelector('footer');
  if(footer&&!footer.querySelector('.language-source-note')) {const note=document.createElement('span');note.className='language-source-note';note.textContent='原始业务资料保留原文。';footer.append(note);}
  syncDocumentLanguage(); localize();
  if (startLocalization.observer || !globalThis.MutationObserver) return;
  const observer = new MutationObserver(mutations => {
    const roots = new Set();
    for (const mutation of mutations) {
      if (mutation.type==='childList') for (const node of mutation.addedNodes) roots.add(node);
      else roots.add(mutation.target);
    }
    for (const root of roots) {
      if (!root.isConnected) continue;
      let ancestor=root.parentNode, covered=false;
      while(ancestor){if(roots.has(ancestor)){covered=true;break;}ancestor=ancestor.parentNode;}
      if(covered)continue;
      if (root.nodeType===1 && root.closest('[data-i18n-skip]')) continue;
      localize(root);
    }
  });
  observer.observe(document.documentElement,{subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:translatedAttributes});
  startLocalization.observer=observer;
}
